test_that("boot_newton minimises a smooth objective from the fitted-curvature start and reports non-convergence", {
  fn <- function(z) sum((z - c(1, -2, 0.5))^2 * c(3, 1, 10)) + 0.1 * sum((z - c(1, -2, 0.5))^4)
  gr <- function(z) 2 * (z - c(1, -2, 0.5)) * c(3, 1, 10) + 0.4 * (z - c(1, -2, 0.5))^3
  H <- boot_hessian(gr, c(1, -2, 0.5))
  expect_equal(H, diag(c(6, 2, 20)), tolerance = 1e-6)
  r <- boot_newton(c(1.3, -1.5, 0.2), fn, gr, solve(H))
  expect_false(is.null(r))
  expect_equal(r$par, c(1, -2, 0.5), tolerance = 1e-3)
  expect_null(boot_newton(c(1.3, -1.5, 0.2), fn, gr, solve(H), maxit = 1L))
  # a non-positive-definite Hessian gives no starting curvature
  expect_null(boot_hessian(function(z) c(1, -1) * z, c(0, 0)))
  expect_null(boot_prepare(function(z) c(1, -1) * z, c(0, 0)))
})

test_that("sdvinecop bootstrap standard errors do not depend on the refit method or the number of cores", {
  skip_on_cran()
  set.seed(21)
  truth <- sdvinecop(arfactcop(lambda = 0.9, w = 0.5), pairs = list(pc("gumbel")), tail = pc("joe"), maxlag = 10, tautol = 1e-3)
  u <- tssim(truth, 500)
  spec <- sdvinecop(arfactcop(order = 1), pairs = list(pc("gumbel")), tail = pc("joe"), maxlag = 10, tautol = 1e-3)
  set.seed(1); f1 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12)
  old <- options(tscop.bootnewton = FALSE)
  set.seed(1); f2 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12)
  options(old)
  expect_equal(f1@boot, f2@boot, tolerance = 1e-3)
  expect_equal(f1@se, f2@se, tolerance = 0.05)
  skip_on_os("windows")
  set.seed(1); f3 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12, cores = 2)
  expect_equal(f1@boot, f3@boot, tolerance = 1e-10)
  # re-ranked (pseudo-observation) replicates give the same result with and without parallelism
  set.seed(2); g1 <- tsfit(u, spec, pseudo = TRUE, se = "bootstrap", B = 12)
  set.seed(2); g2 <- tsfit(u, spec, pseudo = TRUE, se = "bootstrap", B = 12, cores = 2)
  expect_equal(g1@boot, g2@boot, tolerance = 1e-10)
})

test_that("vtscop bootstrap standard errors do not depend on the refit method or the number of cores", {
  skip_on_cran()
  set.seed(22)
  mk <- function(kp) sdvinecop(kp, pairs = list(pc("joe")), tail = pc("joe"), maxlag = 10, tautol = 1e-3)
  truth <- vtscop(mk(arfactcop(lambda = 0.9, w = 0.5)), udp::v2p(0.45, 0.8))
  u <- tssim(truth, 500)
  spec <- vtscop(mk(arfactcop(order = 1)), udp::v2p(0.5, 1))
  set.seed(1); f1 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12)
  old <- options(tscop.bootnewton = FALSE)
  set.seed(1); f2 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12)
  options(old)
  expect_equal(f1@se, f2@se, tolerance = 0.1)
  skip_on_os("windows")
  set.seed(1); f3 <- tsfit(u, spec, pseudo = FALSE, se = "bootstrap", B = 12, cores = 2)
  expect_equal(f1@boot, f3@boot, tolerance = 1e-10)
})

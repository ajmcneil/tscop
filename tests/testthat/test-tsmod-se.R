test_that("bootstrap standard errors are reproducible and do not depend on the number of cores", {
  skip_on_cran()
  set.seed(1)
  m <- tsmod(marg("st", c(mu = 0, sigma = 1, df = 5)), arfactcop(lambda = 0.9, w = 0.6))
  x <- tssim(m, 600)
  set.seed(10); f1 <- tsfit(x, tsmod("st", arfactcop(order = 1)), se = "bootstrap", B = 20)
  set.seed(10); f2 <- tsfit(x, tsmod("st", arfactcop(order = 1)), se = "bootstrap", B = 20)
  expect_equal(f1@se, f2@se)
  skip_on_os("windows")
  set.seed(10); f3 <- tsfit(x, tsmod("st", arfactcop(order = 1)), se = "bootstrap", B = 20, cores = 2)
  expect_equal(f1@se, f3@se, tolerance = 1e-8)
  expect_equal(f1@se_method, "bootstrap")
  expect_equal(dim(f1@boot), c(20L, 5L))
  expect_equal(names(f1@se), names(coef(f1)))
  expect_true(all(f1@se > 0))
  expect_equal(f1@vcov, cov(f1@boot[complete.cases(f1@boot), ]), tolerance = 1e-10)
  expect_equal(unname(sqrt(diag(vcov(f1)))), unname(f1@se))
  expect_output(show(f1), "standard errors: bootstrap")
})

test_that("bootstrap standard errors agree with the asymptotic ones for a Gaussian AR model", {
  skip_on_cran()
  set.seed(2)
  x <- 1 + 2 * as.numeric(arima.sim(list(ar = 0.6), 800))
  a <- arima(x, order = c(1, 0, 0))
  set.seed(3)
  f <- tsfit(x, tsmod("gauss", armacop(order = c(1, 0))), se = "bootstrap", B = 80)
  se_arima <- sqrt(diag(a$var.coef))
  expect_equal(unname(f@se["copula.ar1"]), unname(se_arima["ar1"]), tolerance = 0.3)
  expect_equal(unname(f@se["margin.mu"]), unname(se_arima["intercept"]), tolerance = 0.3)
})

test_that("bootstrap works with an empirical margin and with an automatically chosen margin", {
  skip_on_cran()
  set.seed(4)
  m <- tsmod(marg("nig", c(mu = 0, sigma = 1, shape = 1.5, skew = 0.3)), arfactcop(lambda = 0.9, w = 0.6))
  x <- tssim(m, 800)
  fs <- tsfit(x, tsmod(emarg(x), arfactcop(order = 1)), se = "bootstrap", B = 20)
  expect_equal(names(fs@se), c("copula.lambda1", "copula.w1"))
  expect_true(all(is.finite(fs@se) & fs@se > 0))
  fa <- tsfit(x, tsmod("auto", arfactcop(order = 1)), se = "bootstrap", B = 20,
              automarg_args = list(families = c("gauss", "st", "nig")))
  expect_s4_class(fa@selection, "automarg")
  expect_equal(fa@model@margin@family, fa@selection@best@model@family)
  expect_equal(fa@model@margin@family, "nig")
  expect_equal(names(coef(fa))[1:4], paste0("margin.", c("mu", "sigma", "shape", "skew")))
  expect_true(all(is.finite(fa@se)))
  expect_output(show(fa), "chosen by automarg")
  expect_equal(nrow(fa@selection@table), 3L)
})

test_that("automatic margins and input checks", {
  set.seed(5)
  m <- tsmod("auto", arfactcop(order = 1))
  expect_output(show(m), "automarg")
  expect_error(tssim(m, 10), "chosen automatically")
  x <- tssim(tsmod(marg("sst", c(mu = 0, sigma = 1, df = 6, gamma = 1.4)), arfactcop(lambda = 0.9, w = 0.6)), 1500)
  f <- tsfit(x, m, automarg_args = list(families = c("gauss", "sst"), criterion = "BIC"))
  expect_equal(f@selection@criterion, "BIC")
  expect_equal(f@model@margin@family, "sst")
  expect_equal(coef(f)[["copula.lambda1"]], tsfit(x, tsmod(f@model@margin, arfactcop(order = 1)))@estimate[["copula.lambda1"]], tolerance = 1e-3)
  expect_error(tsfit(x, m, se = "hessian"), "FALSE or")
  expect_error(tsfit(x, m, se = "bootstrap", B = 3), "at least 10")
  # a fitted model with the margin chosen can be used for prediction and simulation
  expect_length(tssim(f, 20), 20)
  expect_length(predict(f, type = "qf", x = c(0.1, 0.9)), 2)
})
